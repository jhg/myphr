<?php

declare(strict_types=1);

namespace App\Models;

use App\Crypto\EnvelopeValidator;
use Database\Factories\ShareLinkFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Concerns\HasVersion4Uuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use LogicException;

/**
 * ADR 0011: the small wrapper of a sharing link.
 *
 * `pin_salt` and `pin_tag` are hidden from the default serialization: the tag is the PIN proof and
 * the salt must only leave through `challenge`, which hands it out deliberately and one at a time.
 * A careless `toArray()` dumping them into a listing response would hand anyone the material to
 * attack the PIN offline, which is exactly the flaw this design fixed.
 *
 * `HasVersion4Uuids` for the same reason as in {@see Share}: the identifier travels in the URL and a
 * UUIDv7 would carry the creation instant inside.
 */
#[Fillable(['id', 'share_id', 'pin_salt', 'pin_tag', 'attempts_remaining', 'wrapper', 'expires_at'])]
#[Hidden(['pin_salt', 'pin_tag', 'wrapper'])]
final class ShareLink extends Model
{
    /** @use HasFactory<ShareLinkFactory> */
    use HasFactory, HasVersion4Uuids;

    /** ADR 0011: the table only has `created_at`. */
    public const UPDATED_AT = null;

    /**
     * Same as {@see Share::$dateFormat} and {@see Event::$dateFormat}: without this, Laravel's
     * default format stores `expires_at` without a fraction of a second.
     *
     * It hurts more here than anywhere else, because this is the expiry `ShareLinkGate::open()`
     * returns to the reader and the one that goes into the `wrapKey` derivation and into the
     * wrapper's associated data (ADR 0011). Lose a single millisecond and the AEAD fails: the
     * professional types the right PIN and sees the tampered-history warning.
     */
    protected $dateFormat = 'Y-m-d H:i:s.u';

    /** Exact length of the salt for the Argon2id of the PIN. */
    public const int PIN_SALT_BYTES = 16;

    /** Exact length of the PIN proof. */
    public const int PIN_TAG_BYTES = 32;

    /**
     * Five attempts per link (ADR 0011). With a six-digit PIN generated by the application, the odds
     * of a lucky guess are 5 in a million.
     */
    public const int MAX_ATTEMPTS = 5;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'expires_at' => 'datetime',
            'attempts_remaining' => 'integer',
        ];
    }

    /**
     * Shape guardrail. The exact lengths are checked here and not in the migration because `binary`
     * does not pin them on SQLite, and a `pin_tag` of a different size would make `hash_equals()`
     * always return `false` without saying why.
     */
    protected static function booted(): void
    {
        self::saving(function (self $link): void {
            if (! is_string($link->pin_salt) || strlen($link->pin_salt) !== self::PIN_SALT_BYTES) {
                throw new LogicException('share_links.pin_salt debe medir exactamente 16 bytes.');
            }

            if (! is_string($link->pin_tag) || strlen($link->pin_tag) !== self::PIN_TAG_BYTES) {
                throw new LogicException('share_links.pin_tag debe medir exactamente 32 bytes.');
            }

            if (! EnvelopeValidator::isValid($link->wrapper)) {
                throw new LogicException('share_links.wrapper does not have the shape of a valid encrypted envelope.');
            }
        });
    }

    /**
     * @return BelongsTo<Share, $this>
     */
    public function share(): BelongsTo
    {
        return $this->belongsTo(Share::class);
    }
}
