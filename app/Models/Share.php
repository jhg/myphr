<?php

declare(strict_types=1);

namespace App\Models;

use App\Crypto\EnvelopeValidator;
use App\Crypto\ShareEnvelopeValidator;
use Database\Factories\ShareFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Concerns\HasVersion4Uuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use LogicException;

/**
 * ADR 0011: the package of a shared clipping, immutable and opaque.
 *
 * The server sees a blob, an identifier and two dates. It does not know what it holds or what range
 * it covers: that lives inside `descriptor`, encrypted under the user's master key, and is decrypted
 * in the browser to paint the active shares screen.
 *
 * `HasVersion4Uuids` and not `HasUuids`: in Laravel 12 the latter generates UUIDv7, which carries
 * the creation instant in the clear inside the identifier, and this identifier ends up in the
 * professional's URL and in the photo of the QR code. It is the exception ADR 0006 already foresees.
 * In practice the identifier arrives generated by the client; the trait stays so a row created
 * without one (a factory, a test) does not reintroduce a v7 by accident.
 *
 * No `SoftDeletes`: revoking and pruning are physical deletes (ADR 0011).
 */
#[Fillable(['id', 'user_id', 'expires_at', 'payload', 'descriptor'])]
final class Share extends Model
{
    /** @use HasFactory<ShareFactory> */
    use HasFactory, HasVersion4Uuids;

    /** ADR 0011: the table only has `created_at`. Nothing is updated in place except `opened_at`. */
    public const UPDATED_AT = null;

    /**
     * Same trait as {@see Event::$dateFormat}, and for the same reason: Laravel's default format,
     * `Y-m-d H:i:s`, truncates microseconds when writing on every engine.
     *
     * `expires_at` is not an administrative date: `canonicalDate(expiresAt)` goes into the `info` of
     * `wrapKey` and into the associated data of the link wrapper (ADR 0011). The client encrypts
     * with the instant it has, milliseconds included; if the server reads it back truncated and
     * returns it that way in `open`, the reader derives a different key and rebuilds different
     * associated data, and the wrapper does not open. With the right PIN, which is the baffling part
     * of the failure. The other half comes from the `precision: 6` columns in the migration, which
     * is what rules on MySQL and PostgreSQL.
     */
    protected $dateFormat = 'Y-m-d H:i:s.u';

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'expires_at' => 'datetime',
            'opened_at' => 'datetime',
        ];
    }

    /**
     * A guardrail on **shape**, never on content, just like {@see Event::booted()}.
     *
     * The two envelopes in this row have different formats and each is checked by its own validator:
     * the package is `s1.` with the ladder from 64 KiB to 4 MiB, and the descriptor is an ordinary
     * `v1.` envelope from ADR 0004. Crossing them is exactly what the different prefix prevents, so
     * the check is written crosswise on purpose.
     */
    protected static function booted(): void
    {
        self::saving(function (self $share): void {
            if (! ShareEnvelopeValidator::isValid($share->payload)) {
                throw new LogicException('shares.payload does not have the shape of a valid encrypted package.');
            }

            if (! EnvelopeValidator::isValid($share->descriptor)) {
                throw new LogicException('shares.descriptor does not have the shape of a valid encrypted envelope.');
            }
        });
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * @return HasMany<ShareLink, $this>
     */
    public function links(): HasMany
    {
        return $this->hasMany(ShareLink::class);
    }
}
