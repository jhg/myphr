/**
 * Clinical reading of an already decrypted clipping (ADR 0011): turning the content of each event
 * into something a professional can read at a glance, without knowing this application and with
 * the appointment already under way.
 *
 * **What is shown and why.** A value without a unit is not a datum, a measurement without a method
 * cannot be compared with another (ADR 0008) and a quantity without its LOINC term cannot be
 * copied into somebody else's health record (ADR 0005). So every row carries all four: date and
 * time, value with unit, how and where it was measured, and the LOINC code with its official term.
 *
 * **The official LOINC term is not translated** (ADR 0005). It is the name that identifies the
 * quantity outside here, in English and exactly as Regenstrief publishes it; translating it would
 * turn it into something else. Everything else is translated.
 *
 * **Nothing is left out in silence.** An event whose content does not have the expected shape is
 * painted as an error row and counted, it never disappears (ADR 0004): in a clipping somebody else
 * is going to read, a missing record is indistinguishable from a record that never existed, and
 * that difference is clinical.
 *
 * This module is pure logic, with no DOM and no network, so it can be tested whole
 * (`tests/js/clinicalReport.test.mjs`). `readerPage.js` is what paints it.
 */

import { formatDateTime, joinList, t } from '../i18n/index.js';

/**
 * Vocabulary resolved for one language, out of the public catalog `App\Sharing\ReaderCatalog`
 * emits.
 *
 * It is resolved once when the language is chosen and not on every row: the catalog brings the
 * three languages inside (so the selector does not have to ask the server for anything) and
 * looking up by language in every cell would repeat the same work per event.
 *
 * @param {object} catalog Content of `data-phr-reader-catalog`.
 * @param {string} locale Active language (`en`, `es`, `zh_CN`).
 * @returns {{labels: Record<string, Record<string, string>>, loinc: Record<string, string>,
 *           units: Record<string, string>}}
 */
export function resolveCatalog(catalog, locale) {
    return {
        labels: catalog?.labels?.[locale] ?? catalog?.labels?.en ?? {},
        loinc: catalog?.loinc ?? {},
        units: catalog?.units ?? {},
    };
}

/**
 * Label of a catalog token.
 *
 * A token this catalog does not know is shown **as is**, never hidden: a datum the application
 * cannot name is still a datum, and hiding it would be lying by omission. It happens, for example,
 * with a clipping generated by a newer version than this page.
 *
 * @param {object} resolved Output of `resolveCatalog`.
 * @param {string} group Catalog group (`glucoseMethods`, `arms`, ...).
 * @param {unknown} token
 * @returns {string|null} `null` when the field was not there (optional ones are left out of the content).
 */
export function labelFor(resolved, group, token) {
    if (typeof token !== 'string' || token === '') {
        return null;
    }

    return resolved.labels?.[group]?.[token] ?? token;
}

/**
 * How a UCUM code is shown. `Cel` reads `°C` and `[lb_av]` reads `lb`: the code is interchange
 * notation, not something anybody should be asked to read (ADR 0005). One that is not in the table
 * is shown as is, for the same reason as an unknown token.
 *
 * @param {object} resolved
 * @param {unknown} code
 * @returns {string}
 */
export function unitLabel(resolved, code) {
    if (typeof code !== 'string' || code === '') {
        return '';
    }

    return resolved.units?.[code] ?? code;
}

/**
 * LOINC codes of an event, with their official term.
 *
 * The content stores the code in `data.loinc`, which is a string in most types and an object with
 * one entry per quantity in blood pressure (systolic, diastolic and pulse are three different
 * quantities, ADR 0005). Both cases come out of here in the same shape.
 *
 * @param {object} resolved
 * @param {unknown} loinc `data.loinc` field exactly as it came.
 * @returns {list<{code: string, name: string|null}>}
 */
export function loincEntries(resolved, loinc) {
    /** @param {unknown} code */
    const entry = (code) => ({ code: String(code), name: resolved.loinc?.[String(code)] ?? null });

    if (typeof loinc === 'string' && loinc !== '') {
        return [entry(loinc)];
    }

    if (loinc !== null && typeof loinc === 'object') {
        return Object.values(loinc)
            .filter((code) => typeof code === 'string' && code !== '')
            .map(entry);
    }

    return [];
}

/**
 * Row of the clinical table out of one event of the package.
 *
 * @param {object} resolved Output of `resolveCatalog`.
 * @param {{occurredAt: string, content: object}} event
 * @returns {{occurredAt: string, occurredAtLabel: string, tz: string|null, typeLabel: string,
 *           value: string, details: list<string>, loinc: list<{code: string, name: string|null}>,
 *           note: string|null, unreadable: boolean}}
 */
export function describeEvent(resolved, event) {
    const content = event?.content;
    const type = typeof content?.type === 'string' ? content.type : '';
    const data = content?.data ?? null;

    const row = {
        occurredAt: typeof event?.occurredAt === 'string' ? event.occurredAt : '',
        occurredAtLabel: typeof event?.occurredAt === 'string' ? formatDateTime(event.occurredAt) : '',
        tz: typeof content?.tz === 'string' ? content.tz : null,
        typeLabel: labelFor(resolved, 'types', type) ?? t('reader.row.unknownType'),
        value: '',
        details: [],
        loinc: [],
        note: typeof content?.note === 'string' && content.note !== '' ? content.note : null,
        unreadable: false,
    };

    if (data === null || typeof data !== 'object') {
        return { ...row, unreadable: true, typeLabel: row.typeLabel, value: t('reader.row.unreadable') };
    }

    const described = describeByType(resolved, type, data);

    if (described === null) {
        return { ...row, unreadable: true, value: t('reader.row.unreadable') };
    }

    row.value = described.value;
    row.details = [...described.details, ...contextDetails(resolved, content)];
    row.loinc = loincEntries(resolved, data.loinc);

    return row;
}

/**
 * The six shareable types (`SHAREABLE_TYPES` in `health/sharePage.js`). A type that is not here
 * returns `null` and ends up painted as an unreadable row, with its date and its type in plain
 * sight: a row saying "not understood" is better than a gap.
 *
 * @param {object} resolved
 * @param {string} type
 * @param {object} data
 * @returns {{value: string, details: list<string>}|null}
 */
function describeByType(resolved, type, data) {
    switch (type) {
        case 'glucose':
            return {
                value: measurement(resolved, data.value, data.unit),
                details: compact([
                    labelFor(resolved, 'glucoseMethods', data.method),
                    labelFor(resolved, 'mealContexts', data.mealContext),
                ]),
            };

        case 'bloodPressure': {
            const pressure = `${plain(data.systolic)}/${plain(data.diastolic)} ${unitLabel(resolved, data.unit)}`.trim();
            const pulse = typeof data.pulse === 'string' && data.pulse !== ''
                ? t('reader.detail.pulse', { value: measurement(resolved, data.pulse, data.pulseUnit) })
                : null;

            return {
                value: pressure,
                details: compact([
                    pulse,
                    labelFor(resolved, 'arms', data.arm),
                    labelFor(resolved, 'postures', data.posture),
                ]),
            };
        }

        case 'insulin':
            return {
                value: measurement(resolved, data.dose, data.unit),
                details: compact([
                    labelFor(resolved, 'insulinTypes', data.insulinType),
                    typeof data.product === 'string' && data.product !== '' ? data.product : null,
                    labelFor(resolved, 'injectionSites', data.site),
                ]),
            };

        case 'meal': {
            const foods = Array.isArray(data.foods) ? data.foods : [];

            return {
                value: labelFor(resolved, 'mealTypes', data.mealType) ?? '',
                details: foods.length === 0
                    ? [t('reader.detail.noFoods')]
                    : foods.map((food) => describeFood(resolved, food)),
            };
        }

        case 'bodyWeight': {
            const height = data.height ?? null;

            return {
                value: measurement(resolved, data.value, data.unit),
                details: compact([
                    height === null
                        ? null
                        : t('reader.detail.height', { value: measurement(resolved, height.value, height.unit) }),
                ]),
            };
        }

        case 'temperature':
            return {
                value: measurement(resolved, data.value, data.unit),
                details: compact([labelFor(resolved, 'temperatureSites', data.site)]),
            };

        default:
            return null;
    }
}

/**
 * Details common to every event (ADR 0006): which device measured it and who wrote it down.
 *
 * **Who wrote it down is always said**, including when it is the person themselves. A record
 * written by a carer and one written by the person are not worth the same in an appointment, and
 * leaving the majority case implicit would force the reader to know which case is the majority.
 *
 * @param {object} resolved
 * @param {object} content
 * @returns {list<string>}
 */
function contextDetails(resolved, content) {
    const device = typeof content.device === 'string' && content.device !== '' ? content.device : null;
    const recordedBy = labelFor(resolved, 'recordedBy', content.recordedBy);

    return compact([
        device === null ? null : t('reader.detail.device', { device }),
        recordedBy === null ? null : t('reader.detail.recordedBy', { who: recordedBy }),
    ]);
}

/**
 * One food of a meal (ADR 0010: quantity and unit are bounded free text, uncoded).
 *
 * @param {object} resolved
 * @param {{name?: string, quantity?: string, unit?: string}} food
 * @returns {string}
 */
function describeFood(resolved, food) {
    const name = typeof food?.name === 'string' ? food.name : '';
    const quantity = typeof food?.quantity === 'string' ? food.quantity : '';
    const unit = labelFor(resolved, 'foodUnits', food?.unit) ?? '';

    if (quantity === '') {
        return name;
    }

    return `${name} · ${quantity} ${unit}`.trim();
}

/**
 * Value with its unit, which is how a clinical datum is read and how it is never stored: inside
 * the envelope the value travels as a **string**, never through `Number`, so no decimal is lost or
 * gained (ADR 0004). It is not converted or reformatted per language here either: `7.8` is what
 * the device showed, and rewriting it as `7,8` would be reinterpreting a measurement.
 *
 * @param {object} resolved
 * @param {unknown} value
 * @param {unknown} unit
 * @returns {string}
 */
export function measurement(resolved, value, unit) {
    return `${plain(value)} ${unitLabel(resolved, unit)}`.trim();
}

/**
 * @param {unknown} value
 * @returns {string}
 */
function plain(value) {
    return typeof value === 'string' || typeof value === 'number' ? String(value) : '';
}

/**
 * @param {list<string|null>} items
 * @returns {list<string>}
 */
function compact(items) {
    return items.filter((item) => typeof item === 'string' && item !== '');
}

/**
 * Sorts by date, from the most recent to the oldest.
 *
 * It is the same order as the six history screens of the panel, and the one that serves whoever
 * opens this: in an appointment you look at this week first. The header states the full range, so
 * the order hides nothing.
 *
 * It sorts a copy: the package body is what was checked against its own `eventCount` and it is not
 * touched.
 *
 * @param {list<{occurredAt: string}>} events
 * @returns {list<object>}
 */
export function sortByDateDescending(events) {
    return [...events].sort((left, right) => Date.parse(right.occurredAt) - Date.parse(left.occurredAt));
}

/**
 * The mandatory header of the clipping: how many events, from when to when and when it was generated.
 *
 * **It is always shown, even when the clipping is empty.** It is what makes a truncated clipping
 * visible: the reader compares the number the header announces with the rows in front of them, and
 * that comparison is the only defence against a transport that delivered less. Without it, a
 * clipping missing the worst week reads as a complete history.
 *
 * @param {object} body Package body in the clear.
 * @returns {{count: string, range: string, generatedAt: string}}
 */
export function reportHeadline(body) {
    const from = body?.range?.from ?? null;
    const to = body?.range?.to ?? null;

    return {
        count: t('reader.header.count', { count: Number(body?.eventCount ?? 0) }),
        range: rangeText(from, to),
        generatedAt: t('reader.header.generated', { at: formatDateTime(body?.generatedAt) }),
    };
}

/**
 * An open range is said with words, never with a gap: "up to 3 June" and "I do not know" are not
 * the same thing, and a lone dash does not tell them apart.
 *
 * @param {string|null} from
 * @param {string|null} to
 * @returns {string}
 */
export function rangeText(from, to) {
    if (from === null && to === null) {
        return t('reader.header.rangeAll');
    }

    if (to === null) {
        return t('reader.header.rangeFrom', { from: formatDateTime(from) });
    }

    if (from === null) {
        return t('reader.header.rangeTo', { to: formatDateTime(to) });
    }

    return t('reader.header.rangeBetween', { from: formatDateTime(from), to: formatDateTime(to) });
}

/**
 * The two type lists, included and excluded, with their labels.
 *
 * **The excluded ones are said out loud.** No meals in the clipping may mean that person does not
 * record meals or that they chose not to show them, and the difference changes the reading: an
 * absence reads as a clinical zero. That is why this line is never folded away or summarized.
 *
 * @param {object} resolved
 * @param {object} body
 * @returns {{included: string, excluded: string|null}}
 */
export function typeSummary(resolved, body) {
    const label = (token) => labelFor(resolved, 'types', token) ?? token;
    const included = Array.isArray(body?.includedTypes) ? body.includedTypes : [];
    const excluded = Array.isArray(body?.excludedTypes) ? body.excludedTypes : [];

    return {
        included: included.length === 0
            ? t('reader.header.includesNothing')
            : t('reader.header.includes', { types: joinList(included.map(label)) }),
        excluded: excluded.length === 0
            ? null
            : t('reader.header.excludes', { types: joinList(excluded.map(label)) }),
    };
}
